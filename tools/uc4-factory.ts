// Generates src/protocol/profiles/uc4FactoryImage.ts from the factory SndA fixture (plan 0004 decision 5).
//   node tools/uc4-factory.ts write   # regenerate the asset
//   node tools/uc4-factory.ts check   # exit 1 if the asset is out of date
// Only reads the fixture and writes the asset; never touches MIDI.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { parseFrame, splitMessages } from '../src/protocol/frame.ts';
import { buildImage, IMAGE_SIZE } from '../src/protocol/image.ts';

const FIXTURE = new URL('../tests/fixtures/sysex/factory-SndA.syx', import.meta.url);
const ASSET = new URL('../src/protocol/profiles/uc4FactoryImage.ts', import.meta.url);

function generate(): string {
  const msgs = splitMessages(new Uint8Array(readFileSync(FIXTURE)));
  const r = parseFrame(msgs[0]!);
  if (msgs.length !== 1 || !r.ok || !r.frame.lossless) throw new Error('factory-SndA.syx is not one lossless message');
  const img = buildImage([r.frame]);
  let from = 0;
  while (from < IMAGE_SIZE && !img.covered[from]) from++;
  let to = from;
  while (to < IMAGE_SIZE && img.covered[to]) to++;
  for (let a = to; a < IMAGE_SIZE; a++) if (img.covered[a]) throw new Error('the factory image has a gap');
  const b64 = Buffer.from(img.bytes.subarray(from, to)).toString('base64');
  const lines = b64.match(/.{1,120}/g)!.map((l) => `  '${l}'`).join(' +\n');
  return `// GENERATED by tools/uc4-factory.ts from tests/fixtures/sysex/factory-SndA.syx (all 18 setups after rESA, firmware 02.05). Do not edit.
// The memory image the factory SndA writes (${to - from} bytes from 0x${from.toString(16)}), base64. The frame around it
// (header, 64-byte records, sums, padding, trailer) is rebuilt by uc4Factory.ts and tested against the fixture.
export const FACTORY_IMAGE_START = 0x${from.toString(16)};
export const FACTORY_IMAGE_BASE64 =
${lines};
`;
}

const mode = process.argv[2];
if (mode === 'write') { writeFileSync(ASSET, generate()); console.log(`wrote ${ASSET.pathname}`); }
else if (mode === 'check') {
  const ok = existsSync(ASSET) && readFileSync(ASSET, 'utf8') === generate();
  console.log(ok ? 'factory asset is up to date' : 'factory asset is OUT OF DATE: run `node tools/uc4-factory.ts write`');
  process.exit(ok ? 0 : 1);
} else { console.error('usage: node tools/uc4-factory.ts write|check'); process.exit(2); }
